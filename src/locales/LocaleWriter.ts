import * as fs from 'fs-extra';
import * as path from 'path';
import { I18nAdapter } from '../adapters/I18nAdapter';
import { Config } from '../config/schema';
import { LocaleWrite } from '../core/types';
import { MessageTree, getNested, setNested, sortTree } from './tree';

/**
 * Turns the flat `key → source text` map into nested locale files.
 *
 * - The source-locale file is authoritative: every key is (re)written with its
 *   source text as the value.
 * - Target-locale files are merged: existing translations are preserved and
 *   only missing keys are added (as empty strings) so translators never lose
 *   work on re-runs.
 *
 * Nothing is written here — {@link buildLocaleWrites} returns planned writes so
 * the pipeline can honour `--dry-run`.
 */
export function buildLocaleWrites(
  config: Config,
  adapter: I18nAdapter,
  keys: Map<string, string>
): LocaleWrite[] {
  const writes: LocaleWrite[] = [];
  const separator = adapter.keySeparator;
  const entries = [...keys.entries()];

  // Source locale — authoritative.
  const sourceTree: MessageTree = {};
  for (const [key, text] of entries) {
    setNested(sourceTree, key.split(separator), text, true);
  }
  writes.push(localeWrite(config, adapter, config.sourceLocale, sourceTree));

  // Target locales — merge, preserving existing translations.
  for (const locale of config.targetLocales) {
    if (locale === config.sourceLocale) continue;
    const existing = readTree(localePath(config, adapter, locale));
    for (const [key] of entries) {
      const segments = key.split(separator);
      const current = getNested(existing, segments);
      setNested(
        existing,
        segments,
        typeof current === 'string' ? current : '',
        true
      );
    }
    writes.push(localeWrite(config, adapter, locale, existing));
  }

  if (config.generateTypeDefs) {
    writes.push(buildTypeDefs(config, entries));
  }

  return writes;
}

/** Apply planned writes to disk, creating directories as needed. */
export async function commitLocaleWrites(writes: LocaleWrite[]): Promise<void> {
  for (const write of writes) {
    if (write.before === write.after) continue;
    await fs.ensureDir(path.dirname(write.path));
    await fs.writeFile(write.path, write.after, 'utf8');
  }
}

/** Resolve a locale file's absolute path for the active adapter. */
export function localePath(
  config: Config,
  adapter: I18nAdapter,
  locale: string
): string {
  return path.join(config.localesDir, adapter.localeRelativePath(locale));
}

function localeWrite(
  config: Config,
  adapter: I18nAdapter,
  locale: string,
  tree: MessageTree
): LocaleWrite {
  const filePath = localePath(config, adapter, locale);
  const before = fs.existsSync(filePath)
    ? fs.readFileSync(filePath, 'utf8')
    : undefined;
  const ordered = config.format.sortKeys ? sortTree(tree) : tree;
  const after = JSON.stringify(ordered, null, config.format.indent) + '\n';
  return { path: filePath, before, after };
}

function buildTypeDefs(config: Config, entries: [string, string][]): LocaleWrite {
  const filePath = path.join(config.localesDir, 'keys.d.ts');
  const union =
    entries.length > 0
      ? entries
          .map(([key]) => `  | ${JSON.stringify(key)}`)
          .sort()
          .join('\n')
      : '  never';
  const after =
    `// Auto-generated by react-auto-i18ner. Do not edit.\n` +
    `export type TranslationKey =\n${union};\n`;
  const before = fs.existsSync(filePath)
    ? fs.readFileSync(filePath, 'utf8')
    : undefined;
  return { path: filePath, before, after };
}

function readTree(filePath: string): MessageTree {
  if (!fs.existsSync(filePath)) return {};
  try {
    const parsed = fs.readJsonSync(filePath);
    return typeof parsed === 'object' && parsed !== null && !Array.isArray(parsed)
      ? (parsed as MessageTree)
      : {};
  } catch {
    return {};
  }
}
